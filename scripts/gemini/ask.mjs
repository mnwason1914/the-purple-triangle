// One-shot Gemini request: node scripts/gemini/ask.mjs --system a.md --in b.md [--in c.md] --task "..." --out out.md
// Falls back across models when one is overloaded (503) or out of free-tier quota (429).
import fs from 'node:fs';

const argv = process.argv.slice(2);
const opt = (k) => { const i = argv.indexOf(k); return i >= 0 ? argv[i + 1] : undefined; };
const many = (k) => argv.flatMap((a, i) => (a === k ? [argv[i + 1]] : []));

for (const line of (fs.existsSync('.env.local') ? fs.readFileSync('.env.local', 'utf8') : '').split('\n')) {
  const m = line.match(/^\s*([A-Z_]+)\s*=\s*(.*)\s*$/);
  if (m && !process.env[m[1]]) process.env[m[1]] = m[2];
}
const KEY = process.env.GEMINI_API_KEY;
if (!KEY) { console.error('GEMINI_API_KEY 없음 (.env.local)'); process.exit(1); }

const MODELS = (opt('--models') ?? 'gemini-3.5-flash,gemini-3-flash-preview,gemini-3.7-flash,gemini-3.8-flash').split(',');
const system = opt('--system') ? fs.readFileSync(opt('--system'), 'utf8') : '';
const parts = many('--in').map((f) => `===== ${f} =====\n${fs.readFileSync(f, 'utf8')}`);
const task = opt('--task-file') ? fs.readFileSync(opt('--task-file'), 'utf8') : (opt('--task') ?? '');
const prompt = [...parts, '===== 과제 =====', task].join('\n\n');
const out = opt('--out');

async function call(model) {
  const body = {
    ...(system ? { systemInstruction: { parts: [{ text: system }] } } : {}),
    contents: [{ role: 'user', parts: [{ text: prompt }] }],
    generationConfig: { temperature: Number(opt('--temp') ?? 0.8), maxOutputTokens: 65536 },
  };
  const r = await fetch(`https://generativelanguage.googleapis.com/v1beta/models/${model}:generateContent`, {
    method: 'POST', headers: { 'content-type': 'application/json', 'x-goog-api-key': KEY },
    body: JSON.stringify(body), signal: AbortSignal.timeout(600000),
  });
  const j = await r.json().catch(() => ({}));
  if (!r.ok) return { status: r.status, msg: j.error?.message ?? '' };
  const c = j.candidates?.[0];
  return { status: 200, text: c?.content?.parts?.map((p) => p.text ?? '').join('') ?? '', finish: c?.finishReason };
}

for (let round = 0; round < 3; round++) {
  for (const model of MODELS) {
    process.stdout.write(`${model} … `);
    let res;
    try { res = await call(model); } catch (e) { console.log('응답 없음', e.name); continue; }
    if (res.status !== 200) { console.log(res.status, res.msg.slice(0, 80)); continue; }
    console.log(`완료 (${res.text.length}자, ${res.finish})`);
    const header = `<!-- generated by ${model} · ${new Date().toISOString()} -->\n`;
    if (out) fs.writeFileSync(out, header + res.text.trim() + '\n'); else console.log(res.text);
    process.exit(0);
  }
  console.log(`모든 모델이 바쁨. ${30 * (round + 1)}초 뒤 다시`);
  await new Promise((ok) => setTimeout(ok, 30000 * (round + 1)));
}
process.exit(1);
